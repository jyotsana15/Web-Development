// Q3. Math Utility Dashboard

// Take a number x
const x = 16.75;

// Display rounded value, square root, power, and a random number
console.log(`For the number ${x}:`);
console.log(`Rounded value: ${Math.round(x)}`);
console.log(`Square root: ${Math.sqrt(x)}`);
console.log(`Value to the power of 3: ${Math.pow(x, 3)}`);
console.log(`Random number between 10 and 50: ${Math.floor(Math.random() * 41) + 10}`);
